#!/usr/bin/env python3
"""Generate the compact front-plane HRTF grid from MIT's original ZIP.
Usage: python3 tools/generate_spatial_data.py /path/to/compact.zip
No runtime downloads. Original data: Gardner & Martin, MIT Media Lab (1994).
"""
import hashlib, io, math, re, struct, sys, wave, zipfile
from pathlib import Path
archive = Path(sys.argv[1])
raw = archive.read_bytes()
z = zipfile.ZipFile(io.BytesIO(raw))
def response(elevation, azimuth):
    candidates = []
    for name in z.namelist():
        m = re.search(r'H(-?\d+)e(\d+)a\.wav$', name)
        if m and int(m[1]) == elevation:
            candidates.append((abs(int(m[2])-azimuth), name))
    _, name = min(candidates)
    w = wave.open(io.BytesIO(z.read(name)))
    assert (w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()) == (2, 2, 44100, 128)
    data = struct.unpack('<256h', w.readframes(128))
    return name, [list(data[::2]), list(data[1::2])]
front = response(0,0)[1]
gain = 1/math.sqrt(sum((v/32768)**2 for ear in front for v in ear))
lines = ['/* Generated by tools/generate_spatial_data.py. Do not edit.',
         ' * Copyright 1994 MIT Media Laboratory. Measurements by Bill Gardner and Keith Martin.',
         ' * Use permitted with attribution; see documentation/third-party-notices.md.',
         ' * Source: https://sound.media.mit.edu/resources/KEMAR/compact.zip',
         f' * Archive SHA-256: {hashlib.sha256(raw).hexdigest()} */',
         '#ifndef TI_SYNTH_HRTF_DATA_H', '#define TI_SYNTH_HRTF_DATA_H', '#include <stdint.h>',
         f'#define SYNTH_HRTF_GAIN {gain:.12f}f',
         'static const int16_t synth_hrtf_grid[3][3][2][128] = {']
for elevation in [-40,0,40]:
    lines.append('  {')
    for x in [-1,0,1]:
        name, ears = response(elevation, abs(x)*60)
        if x<0: ears=ears[::-1]
        lines.append(f'    {{ /* x={x}, elevation={elevation}; {name}'+(' mirrored' if x<0 else '')+' */')
        for ear in ears:
            lines.append('      {'+','.join(map(str,ear))+'},')
        lines.append('    },')
    lines.append('  },')
lines.extend(['};','#endif',''])
Path(__file__).resolve().parents[1].joinpath('shared/synth_hrtf_data.h').write_text('\n'.join(lines))
print('Generated 9 stereo HRIRs; front-pair energy normalization:', gain)
